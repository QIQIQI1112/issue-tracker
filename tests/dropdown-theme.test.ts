import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createElement } from 'react';
import { Dropdown } from '../src/ui/components/Dropdown.tsx';
import { Fixture, IssueFixture, issue, open } from './dropdown-fixture.ts';

test('dropdown retains complete long labels and distinguishes selected indicators from active navigation', async () => {
  const fixture = new Fixture();
  const selections: string[] = [];
  try {
    const labels = Array.from({ length: 60 }, (_, index) => `Option ${String(index).padStart(2, '0')} ${'long_unbroken_identifier_'.repeat(8)}`);
    await fixture.mount(createElement(IssueFixture, { records: [issue(37, { labels })], onLabelChange: value => selections.push(value) }));
    const trigger = await open(fixture, 'Filter by label');
    const chevron = trigger.querySelector('.dropdown-chevron');
    assert.ok(chevron);
    assert.equal(chevron.getAttribute('viewBox'), '0 0 24 24');
    assert.equal(chevron.querySelector('path')?.getAttribute('d'), 'm6 9 6 6 6-6');
    assert.equal(chevron.getAttribute('aria-hidden'), 'true');
    assert.deepEqual(fixture.options().map(option => option.textContent), ['All labels', ...labels], 'Every complete current identity remains available to the actual listbox.');
    await fixture.key(trigger, 'End');
    assert.equal(fixture.active(trigger)?.textContent, labels.at(-1));
    assert.deepEqual(selections, [], 'Active navigation does not commit an option.');
    await fixture.key(trigger, 'Enter');
    assert.deepEqual(selections, [labels.at(-1)]);
    assert.equal(trigger.querySelector('.dropdown-value')?.textContent, labels.at(-1));
    assert.equal(trigger.getAttribute('aria-label'), 'Filter by label');
    assert.equal(fixture.document.activeElement, trigger);
    await open(fixture, 'Filter by label');
    await fixture.key(trigger, 'Home');
    assert.equal(fixture.active(trigger)?.textContent, 'All labels');
    const selected = fixture.options().find(option => option.getAttribute('aria-selected') === 'true');
    assert.ok(selected);
    assert.equal(selected.textContent, labels.at(-1));
    assert.equal(selected.dataset.active, 'false');
    const check = selected.querySelector('.dropdown-check');
    assert.ok(check);
    assert.equal(check.getAttribute('viewBox'), '0 0 24 24');
    assert.equal(check.getAttribute('stroke'), 'currentColor');
    assert.equal(check.getAttribute('aria-hidden'), 'true');
    assert.equal(check.querySelector('path')?.getAttribute('d'), 'M20 6 9 17l-5-5');
    assert.equal(selected.lastElementChild, check, 'The selected Check trails the complete label.');
    assert.equal(fixture.active(trigger)?.querySelector('.dropdown-check'), null, 'The active unselected placeholder cannot acquire the selected indicator.');
    assert.equal(fixture.options().filter(option => option.querySelector('.dropdown-check')).length, 1);
    assert.deepEqual(selections, [labels.at(-1)]);
    await fixture.key(trigger, 'Escape');
    await fixture.mount(createElement(Dropdown, { value: 'one', onChange: () => {}, 'aria-label': 'Grouped dropdown' }, createElement('optgroup', { label: 'Current group' }, createElement('option', { value: 'one' }, 'One'))));
    await open(fixture, 'Grouped dropdown');
    const group = fixture.root.querySelector('[role="group"]');
    assert.equal(group?.getAttribute('aria-label'), 'Current group');
    assert.equal(group?.querySelector('.dropdown-group-label')?.textContent, 'Current group');
    assert.deepEqual(fixture.options().map(option => option.textContent), ['One']);
  } finally { await fixture.dispose(); }
});
