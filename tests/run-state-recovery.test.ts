function recoveryFixture(context: TestContext) {
  context.mock.timers.enable({ apis: ['Date'], now: Date.parse('2026-01-02T03:04:05.000Z') });
  const root = evidenceDirectory('run-state-recovery');
  const repository = fixtureRepository(join(root, 'repo'));
  const store = new IssueStore(join(root, 'state.sqlite'));
  context.after(() => store.close());
  const repo = store.work.addRepo({ name: 'Fixture', path: repository, targetBranch: 'main' });
  const issue = store.create({ title: 'Ready value', description: 'Return ready.', status: 'open', priority: 'medium', labels: [], work: { repoId: repo.id, requirementId: null, dependsOn: [], acceptance: ['The value is ready.'] } });
  store.work.startIssue(issue.id);
  const claim = store.work.claim(root)!;
  assert.equal(claim.job.issueId, issue.id, 'Fixture readiness: the native claim belongs to the requested issue.');
  const directory = claim.run.evidencePath;
  mkdirSync(directory, { recursive: true });
  const task = parseTask({ schemaVersion: 2, id: `issue-${issue.id}`, title: issue.title, goal: issue.description, acceptance: [{ id: 'ready', description: issue.work!.acceptance[0] }], scope: ['src/', 'tests/'], verificationCommand: 'npm run verify', budget: { maxAttempts: 3, workerTimeoutMs: 2000, totalTimeoutMs: 30000 } });
  const source = snapshot(repository);
  const stages = new StageRunner(directory, task, repository, source.hash, claim.run.id);
  context.mock.timers.tick(25);
  stages.enter('plan', repository);
  const progress = parseRunState(readJson(join(directory, 'run-state.json')));
  const state: ControllerState = { schemaVersion: 1, runId: claim.run.id, taskId: task.id, runDirectory: directory, workspace: join(directory, 'workspace'), status: 'running', phase: 'plan', startedAt: claim.run.startedAt, cleanupSafe: true, sourceHash: source.hash, baseCommit: git(repository, ['rev-parse', 'HEAD']).trim(), baselineTree: git(repository, ['rev-parse', 'HEAD^{tree}']).trim(), redChecks: [], attempts: [], phases: [{ name: 'prepare', startedAt: progress.transitions[0].startedAt, completedAt: progress.transitions[0].completedAt, durationMs: 25, status: 'passed' }, { name: 'plan', startedAt: progress.transitions[1].startedAt, durationMs: 0, status: 'running' }] };
  writeJson(join(directory, 'task.json'), task);
  writeJson(join(directory, 'state.json'), state);
  assert.doesNotThrow(() => assertRunQuiescent(directory), 'Fixture readiness: retained execution has no live owner.');
  assert.equal(store.work.run(claim.run.id)?.status, 'running', 'Fixture readiness: recovery starts from a native running claim.');
  const queue = new SerialQueue(store, { evidenceRoot: root });
  const observe = () => ({ progress: parseRunState(readJson(join(directory, 'run-state.json'))), state: readJson(join(directory, 'state.json')) as ControllerState, delivery: readJson(join(directory, 'delivery.json')) as Delivery, run: store.work.run(claim.run.id)!, job: store.work.jobs().find(job => job.id === claim.job.id)!, issue: store.get(issue.id) });
  return { context, repository, directory, store, claim, task, stages, state, progress, source, queue, observe };
}

function assertBlocked(fixture: ReturnType<typeof recoveryFixture>, reason: string, stage: string) {
  const observed = fixture.observe();
  assert.deepEqual({ progress: observed.progress.status, stage: observed.progress.stage, state: observed.state.status, delivery: observed.delivery.status, index: observed.run.status }, { progress: 'blocked', stage: 'blocked', state: 'blocked', delivery: 'blocked', index: 'blocked' }, 'Native recovery must persist the blocked outcome in typed progress, detailed state, standard delivery and the native index.');
  assert.deepEqual([observed.progress.runId, observed.state.runId, observed.delivery.runId, observed.run.id, observed.job.runId], Array(5).fill(fixture.claim.run.id), 'Every recovered representation must identify the actual native run.');
  assert.deepEqual([observed.progress.taskId, observed.state.taskId, observed.delivery.taskId], Array(3).fill(fixture.task.id), 'Recovery must retain the matching task identity.');
  assert.equal(observed.run.jobId, fixture.claim.job.id);
  assert.equal(observed.run.issueId, fixture.claim.job.issueId);
  assert.equal(observed.job.status, 'blocked');
  assert.equal(observed.issue?.status, 'blocked');
  assert.equal(observed.run.reason, reason, 'The native index must retain the actionable originating failure.');
  assert.equal(observed.job.reason, reason);
  assert.equal(observed.state.reason, reason);
  assert.equal(observed.progress.failure?.message, reason);
  assert.equal(observed.progress.failure?.stage, stage);
  assert.ok(observed.progress.failure?.kind.trim(), 'Typed blocking needs a structured failure kind.');
  assert.ok(observed.delivery.summary?.includes(reason), 'The current delivery result must explain the originating failure.');
  assert.ok(observed.delivery.limitations.includes(reason));
  for (const path of ['run-state.json', 'state.json']) assert.equal(observed.delivery.evidence.find(item => item.path === path)?.sha256, digest(readFileSync(join(fixture.directory, path))), `The delivery manifest must bind the reconciled ${path} bytes.`);
  return observed;
}

function assertRepeatSafe(fixture: ReturnType<typeof recoveryFixture>) {
  const before = fixture.observe();
  const files = ['run-state.json', 'state.json', 'delivery.json', 'delivery.md'];
  const bytes = files.map(file => readFileSync(join(fixture.directory, file), 'utf8'));
  fixture.context.mock.timers.tick(1000);
  fixture.queue.recover();
  assert.deepEqual(fixture.observe(), before, 'Repeated native recovery must preserve terminal timestamps, failure context and indexed outcomes.');
  assert.deepEqual(files.map(file => readFileSync(join(fixture.directory, file), 'utf8')), bytes, 'Repeated reconciliation must leave terminal evidence stable.');
}

test('native recovery blocks an interrupted modern planning run consistently without a prior delivery', context => {
  const fixture = recoveryFixture(context);
  assert.equal(existsSync(join(fixture.directory, 'delivery.json')), false, 'Fixture readiness: no delivery exists before interrupted planning recovery.');
  context.mock.timers.tick(5000);
  const reconciledAt = new Date().toISOString();
  fixture.queue.recover();
  const observed = assertBlocked(fixture, 'Queue worker was interrupted. Inspect retained evidence before retrying.', 'planning');
  assert.equal(observed.state.failedPhase, 'plan');
  assert.equal(observed.state.completedAt, reconciledAt, 'An interruption with no prior terminal instant must use the reconciliation time.');
  assert.equal(observed.delivery.completedAt, reconciledAt);
  assert.deepEqual(observed.progress.engine, fixture.progress.engine);
  assert.equal(observed.progress.sourceHash, fixture.source.hash);
  assert.deepEqual(observed.progress.proofs, fixture.progress.proofs);
  assert.deepEqual(observed.progress.transitions[0], fixture.progress.transitions[0], 'Already completed typed timing must remain unchanged.');
  assert.deepEqual(observed.progress.transitions.find(phase => phase.stage === 'planning'), { ...fixture.progress.transitions[1], completedAt: reconciledAt, durationMs: 5000 }, 'Recovery must close the actual active typed interval once.');
  assert.deepEqual(observed.state.phases?.[0], fixture.state.phases?.[0]);
  assert.deepEqual(observed.state.phases?.find(phase => phase.name === 'plan'), { ...fixture.state.phases![1], completedAt: reconciledAt, durationMs: 5000, status: 'failed' }, 'Recovery must close the active detailed phase without erasing its elapsed time.');
  assert.deepEqual(observed.delivery.phases, observed.state.phases);
  assertRepeatSafe(fixture);
});

test('native recovery reconciles an existing delivery while preserving failure context timing proofs and attempts', context => {
  const fixture = recoveryFixture(context);
  context.mock.timers.tick(75);
  fixture.stages.enter('tests', fixture.repository);
  const checks = fixture.source.files.filter(file => file.path.startsWith('tests/'));
  writeJson(join(fixture.directory, 'accepted-checks.json'), checks);
  writeJson(join(fixture.directory, 'coverage.json'), { approved: true, purpose: 'acceptance-coverage', criteriaHash: digest(JSON.stringify(fixture.task.acceptance)) });
  fixture.stages.acceptChecks(fixture.repository, 'coverage.json');
  context.mock.timers.tick(50);
  fixture.stages.enter('implement', fixture.repository);
  const progress = parseRunState(readJson(join(fixture.directory, 'run-state.json')));
  context.mock.timers.tick(4000);
  const completedAt = new Date().toISOString();
  const reason = 'Implementation worker exited with code 7 while updating src/value.ts; inspect worker-2.json before retrying.';
  const state: ControllerState = { ...fixture.state, status: 'blocked', phase: 'implement', failedPhase: 'implement', failureKind: 'worker', reason, completedAt, attempts: [{ id: `${fixture.claim.run.id}-1`, number: 1 }, { id: `${fixture.claim.run.id}-2`, number: 2 }], budget: { usedMs: 4150, implementationAttempts: 2, acceptanceAttempts: 1, infrastructureRetries: 0, maxAttempts: 3, totalTimeoutMs: 30000 }, phases: progress.transitions.map(phase => ({ name: ({ admission: 'prepare', planning: 'plan', checks: 'tests', implementation: 'implement' } as Record<string, string>)[phase.stage], startedAt: phase.startedAt, completedAt: phase.completedAt ?? completedAt, durationMs: phase.completedAt ? phase.durationMs : 4000, status: phase.completedAt ? 'passed' : 'failed' })) };
  writeJson(join(fixture.directory, 'worker-2.json'), { schemaVersion: 1, taskId: fixture.task.id, summary: 'The worker stopped before completing the requested value change.', blockers: [reason] });
  writeJson(join(fixture.directory, 'state.json'), state);
  const delivery = controllerDelivery(state, fixture.task);
  const retainedFiles = ['accepted-checks.json', 'coverage.json', 'worker-2.json', 'task.json'];
  const retainedBytes = retainedFiles.map(file => readFileSync(join(fixture.directory, file), 'utf8'));
  assert.equal(delivery.status, 'blocked', 'Fixture readiness: a pre-existing delivery carries the original worker failure.');
  assert.equal(progress.stage, 'implementation', 'Fixture readiness: typed progress remains interrupted before terminal reconciliation.');
  context.mock.timers.tick(10000);
  assert.doesNotThrow(() => assertRunQuiescent(fixture.directory));
  fixture.queue.recover();
  const observed = assertBlocked(fixture, reason, 'implementation');
  assert.equal(observed.progress.failure?.kind, 'worker');
  assert.equal(observed.state.failureKind, 'worker');
  assert.equal(observed.state.failedPhase, 'implement');
  assert.equal(observed.state.completedAt, completedAt, 'Recovery must preserve an established terminal instant.');
  assert.equal(observed.delivery.completedAt, completedAt);
  assert.deepEqual(observed.state.phases, state.phases, 'Known completed detailed timing must not be rewritten at reconciliation.');
  assert.deepEqual(observed.delivery.phases, state.phases);
  assert.deepEqual(observed.progress.transitions.slice(0, progress.transitions.length - 1), progress.transitions.slice(0, -1), 'Previously completed typed intervals must remain unchanged.');
  assert.deepEqual(observed.progress.transitions.find(phase => phase.stage === 'implementation'), { ...progress.transitions.at(-1), completedAt, durationMs: 4000 }, 'The interrupted typed interval must close at the established terminal instant.');
  assert.deepEqual(observed.progress.engine, progress.engine);
  assert.equal(observed.progress.sourceHash, progress.sourceHash);
  assert.deepEqual(observed.progress.proofs, progress.proofs, 'Blocking must preserve modern proof identities without admitting completion.');
  assert.deepEqual(observed.state.attempts, state.attempts);
  assert.deepEqual(observed.state.budget, state.budget);
  assert.equal(observed.state.baseCommit, state.baseCommit);
  assert.equal(observed.state.baselineTree, state.baselineTree);
  assert.equal(observed.state.sourceHash, state.sourceHash);
  assert.equal(observed.delivery.attempts, 2);
  assert.deepEqual(observed.delivery.budget, state.budget);
  assert.deepEqual(observed.delivery.workerObservations, delivery.workerObservations);
  assert.deepEqual(retainedFiles.map(file => readFileSync(join(fixture.directory, file), 'utf8')), retainedBytes, 'Recovery must preserve accepted check bytes and original worker evidence.');
  assertRepeatSafe(fixture);
});
